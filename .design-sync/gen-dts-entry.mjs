#!/usr/bin/env node
// Generates repo-root /index.d.ts — a barrel over every .d.ts emitted by
// `tsc -p .design-sync/tsconfig.dts.json` into /types/src/components/**.
//
// Why this exists: design-sync's prop extraction (lib/dts.mjs propsBodyFor)
// has two lookup paths. The first (an explicit `<Name>Props` interface/type
// alias) doesn't apply here — our components use inline destructured params,
// not named Props types. The fallback path derives props from the exported
// declaration's call signature, but it ONLY looks in ONE file:
// `project.getSourceFile(entry)`, where `entry` is `pkgJson.types ||
// pkgJson.typings || 'index.d.ts'` under the package root. This repo's
// package.json has neither field, so `entry` resolves to repo-root
// `index.d.ts` — without this barrel, that file doesn't exist, the fallback
// silently returns null, and every component's .d.ts comes out as an empty
// `{ [key: string]: unknown }` stub.
//
// gitignored, regenerated by prepare-scoped-src.sh before every build.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = 'types/src/components';
const groups = ['ui', 'form-fields', 'layouts', 'loaders', 'modals', 'navigation', 'containers', 'svg'];

function walk(dir, out = []) {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (e.endsWith('.d.ts')) out.push(p);
  }
  return out;
}

const lines = [];
for (const g of groups) {
  const dir = join(root, g);
  let files;
  try { files = walk(dir); } catch { continue; }
  for (const f of files) {
    const spec = './' + relative('.', f).replace(/\.d\.ts$/, '');
    if (f === join(root, 'form-fields', 'checkbox.d.ts')) {
      // Renamed in the scoped-src copy (see prepare-scoped-src.sh) to avoid
      // colliding with ui/checkbox.tsx's own `Checkbox` export — mirror that
      // rename here via an aliased re-export instead of `export *`, so the
      // barrel's "CheckboxField" lookup resolves to the real declaration.
      lines.push(`export { Checkbox as CheckboxField } from ${JSON.stringify(spec)};`);
      continue;
    }
    lines.push(`export * from ${JSON.stringify(spec)};`);
  }
}
writeFileSync('index.d.ts', lines.join('\n') + '\n');
console.error(`  [DTS_ENTRY] wrote index.d.ts (${lines.length} re-exports)`);
